	b.WriteString("## Full Catalog\n\n")
	fmt.Fprintf(&b, "Run `%s commands --json` to inspect the generated command catalog. Use `--include-hidden` only when hidden commands are relevant.\n\n", cli)
	b.WriteString("Key fields:\n\n")
